export const catalog: Record<Lang, Record<MessageKey, string>> = { zh, en };

export function translate(
  lang: Lang,
  key: MessageKey,
  vars?: Record<string, string | number>,
) {
  const template = catalog[lang][key] ?? catalog.zh[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/** Translate outside React (stores, event handlers) using the saved language. */
export function tNow(key: MessageKey, vars?: Record<string, string | number>) {
  return translate(useSettings.getState().lang, key, vars);
}

/** Reads the language from the persisted settings store. */
export function useI18n() {
  const lang = useSettings((s) => s.lang);
  const t = useCallback(
    (key: MessageKey, vars?: Record<string, string | number>) =>
      translate(lang, key, vars),
    [lang],
  );
  return { lang, t };
}
